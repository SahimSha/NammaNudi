import { useState, useEffect, useCallback, useRef } from 'react';
import { speechService } from '../utils/speech';
import type { VoiceStatus, SpeechErrorReason } from '../utils/speech';
import { audioPlayerService } from '../utils/audioPlayer';
import { getPhraseAudioUrl } from '../data/audioRegistry';

export interface UseSpeechOptions {
  onErrorNotice?: (message: string) => void;
}

export function useSpeech(options?: UseSpeechOptions) {
  const [isSpeaking, setIsSpeaking] = useState<boolean>(false);
  const [isLoading, setIsLoading] = useState<boolean>(false);
  const [activePhraseId, setActivePhraseId] = useState<string | null>(null);
  const [voiceStatus, setVoiceStatus] = useState<VoiceStatus>(() =>
    speechService.getVoiceStatus()
  );

  const optionsRef = useRef(options);
  useEffect(() => {
    optionsRef.current = options;
  }, [options]);

  useEffect(() => {
    const updateVoiceStatus = () => {
      setVoiceStatus(speechService.getVoiceStatus());
    };

    updateVoiceStatus();
    const unsubscribe = speechService.subscribe(updateVoiceStatus);

    return () => {
      unsubscribe();
    };
  }, []);

  const stop = useCallback(() => {
    speechService.stop();
    audioPlayerService.stop();
    setIsLoading(false);
    setIsSpeaking(false);
    setActivePhraseId(null);
  }, []);

  const speak = useCallback(
    (
      text: string,
      callbacks?: {
        onStart?: () => void;
        onEnd?: (wasAudioProduced: boolean) => void;
        onError?: (reason: string) => void;
      },
      phraseId?: string
    ) => {
      // Cleanly stop any existing speech or audio playback
      speechService.stop();
      audioPlayerService.stop();
      setIsLoading(false);
      setIsSpeaking(false);
      setActivePhraseId(phraseId || null);

      const currentStatus = speechService.getVoiceStatus();
      const prerecordedUrl = phraseId ? getPhraseAudioUrl(phraseId) : null;

      // Helper to speak via native browser SpeechSynthesis (kn-IN)
      const speakViaTts = () => {
        setIsLoading(false);
        setIsSpeaking(true);
        const ttsInitiated = speechService.speak(text, {
          onStart: () => {
            setIsSpeaking(true);
            callbacks?.onStart?.();
          },
          onEnd: (wasAudioProduced: boolean) => {
            setIsSpeaking(false);
            setActivePhraseId(null);
            if (wasAudioProduced) {
              callbacks?.onEnd?.(true);
            } else {
              // Immediate silent completion (host lacks voice despite report)
              callbacks?.onError?.('immediate-silent-end');
              optionsRef.current?.onErrorNotice?.(
                'Kannada audio could not be generated by your device. Please use the phonetic pronunciation guide!'
              );
            }
          },
          onError: (reason: SpeechErrorReason) => {
            setIsSpeaking(false);
            setActivePhraseId(null);
            if (reason === 'canceled' || reason === 'interrupted') {
              callbacks?.onError?.(reason);
              return;
            }
            callbacks?.onError?.(reason);
            optionsRef.current?.onErrorNotice?.(
              'Kannada speech playback error. Please refer to the phonetic pronunciation guide.'
            );
          }
        });

        if (!ttsInitiated) {
          setIsSpeaking(false);
          setActivePhraseId(null);
          callbacks?.onError?.('tts-initiation-failed');
        }
      };

      // 1. If an authentic local recording exists for this phrase, prioritize it
      if (prerecordedUrl) {
        setIsLoading(true);
        const audioStarted = audioPlayerService.play(prerecordedUrl, {
          onLoading: () => {
            setIsLoading(true);
          },
          onStart: () => {
            setIsLoading(false);
            setIsSpeaking(true);
            callbacks?.onStart?.();
          },
          onEnd: () => {
            setIsLoading(false);
            setIsSpeaking(false);
            setActivePhraseId(null);
            callbacks?.onEnd?.(true);
          },
          onError: () => {
            setIsLoading(false);
            setActivePhraseId(null);
            // If prerecorded audio fails to play, fall back to native Kannada TTS if available
            if (currentStatus.hasKannadaVoice) {
              speakViaTts();
            } else {
              setIsSpeaking(false);
              callbacks?.onError?.('audio-playback-failed');
              optionsRef.current?.onErrorNotice?.(
                'Failed to play prerecorded Kannada audio. Please refer to the phonetic guide.'
              );
            }
          }
        });

        if (!audioStarted) {
          setIsLoading(false);
          if (currentStatus.hasKannadaVoice) {
            speakViaTts();
          } else {
            setIsSpeaking(false);
            setActivePhraseId(null);
          }
        }
        return;
      }

      // 2. If no prerecorded audio exists, but a native Kannada voice is installed, use TTS
      if (currentStatus.hasKannadaVoice) {
        speakViaTts();
        return;
      }

      // 3. Neither a registered recording nor a native Kannada voice is available on this device
      setIsLoading(false);
      setIsSpeaking(false);
      setActivePhraseId(null);
      callbacks?.onError?.('no-kannada-audio');
      optionsRef.current?.onErrorNotice?.(
        'Kannada audio unavailable on this device: Windows/browser lacks a native Kannada TTS voice, and no offline recording has been added for this phrase yet. Please use the phonetic pronunciation guide!'
      );
    },
    []
  );

  return {
    speak,
    stop,
    isSpeaking,
    isLoading,
    activePhraseId,
    voiceStatus,
    hasKannadaVoice: voiceStatus.hasKannadaVoice
  };
}
